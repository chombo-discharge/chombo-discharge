#ifndef CD_ITOKMCSURFACEREACTION_H
#define CD_ITOKMCSURFACEREACTION_H

// Std includes
#include <list>

// Chombo includes
#include <REAL.H>

// Our includes
#include <CD_NamespaceHeader.H>

namespace Physics {
namespace ItoKMC {

/**
 * @brief Reaction class for describing secondary emissions due to a single outgoing particle in ItoKMCPhysics.
 * @details This class supports multiple emissions due to single impinging particles, and encapsulates all reactions A
 * -> B, A -> B + C, etc.
 *
 * A reaction can also consume and produce surface species. In an impact reaction the reactant is the impinging
 * plasma or photon species, the surface reactants are surface species that the impact consumes, and the efficiency
 * is the probability of the pathway. In a first-order surface reaction the reactant is the index of the surface
 * species that decays, the list of surface reactants is empty, and the efficiency holds the rate constant (1/s).
 */
class ItoKMCSurfaceReaction
{
public:
  /**
   * @brief Allowed, but you need to call the define function afterwards.
   */
  ItoKMCSurfaceReaction() = default;

  /**
   * @brief Full constructor. Calls the define function.
   * @param[in] a_reactant   Index in the list of plasma or photon species that triggers the reaction.
   * @param[in] a_products   List of plasma species potentially generated by the reaction.
   * @param[in] a_efficiency Reaction efficiency
   */
  inline ItoKMCSurfaceReaction(const size_t            a_reactant,
                               const std::list<size_t> a_products,
                               const Real              a_efficiency) noexcept;

  /**
   * @brief Full constructor for reactions that involve surface species. Calls the define function.
   * @param[in] a_reactant         Index of the impinging plasma or photon species, or of the decaying surface
   *                               species for a first-order surface reaction.
   * @param[in] a_products         List of plasma species potentially generated by the reaction.
   * @param[in] a_surfaceReactants List of surface species consumed by the reaction.
   * @param[in] a_surfaceProducts  List of surface species produced by the reaction.
   * @param[in] a_efficiency       Reaction efficiency, or the rate constant (1/s) for a first-order surface
   *                               reaction.
   */
  inline ItoKMCSurfaceReaction(const size_t            a_reactant,
                               const std::list<size_t> a_products,
                               const std::list<size_t> a_surfaceReactants,
                               const std::list<size_t> a_surfaceProducts,
                               const Real              a_efficiency) noexcept;

  /**
   * @brief Destructor.
   */
  virtual inline ~ItoKMCSurfaceReaction() noexcept;

  /**
   * @brief Full define function.
   * @param[in] a_reactant   Index in the list of plasma or photon species that triggers the reaction.
   * @param[in] a_products   List of plasma species potentially generated by the reaction.
   * @param[in] a_efficiency Reaction efficiency
   */
  inline void
  define(const size_t a_reactant, const std::list<size_t> a_products, const Real a_efficiency) noexcept;

  /**
   * @brief Full define function for reactions that involve surface species.
   * @param[in] a_reactant         Index of the impinging plasma or photon species, or of the decaying surface
   *                               species for a first-order surface reaction.
   * @param[in] a_products         List of plasma species potentially generated by the reaction.
   * @param[in] a_surfaceReactants List of surface species consumed by the reaction.
   * @param[in] a_surfaceProducts  List of surface species produced by the reaction.
   * @param[in] a_efficiency       Reaction efficiency, or the rate constant (1/s) for a first-order surface
   *                               reaction.
   */
  inline void
  define(const size_t            a_reactant,
         const std::list<size_t> a_products,
         const std::list<size_t> a_surfaceReactants,
         const std::list<size_t> a_surfaceProducts,
         const Real              a_efficiency) noexcept;

  /**
   * @brief Get the reactant species index (const).
   * @return Index into the plasma/photon species list that triggers this reaction.
   */
  inline const size_t&
  getReactant() const noexcept;

  /**
   * @brief Get the reactant species index (mutable).
   * @return Index into the plasma/photon species list that triggers this reaction.
   */
  inline size_t&
  getReactant() noexcept;

  /**
   * @brief Get the plasma product species indices (const).
   * @return List of indices into the plasma species list produced by this reaction.
   */
  inline const std::list<size_t>&
  getProducts() const noexcept;

  /**
   * @brief Get the plasma product species indices (mutable).
   * @return List of indices into the plasma species list produced by this reaction.
   */
  inline std::list<size_t>&
  getProducts() noexcept;

  /**
   * @brief Get the surface species consumed by the reaction.
   * @return List of indices into the surface species list.
   */
  inline const std::list<size_t>&
  getSurfaceReactants() const noexcept;

  /**
   * @brief Get the surface species produced by the reaction.
   * @return List of indices into the surface species list.
   */
  inline const std::list<size_t>&
  getSurfaceProducts() const noexcept;

  /**
   * @brief Get the reaction efficiency (const).
   * @return Probability that an impinging particle triggers this reaction.
   */
  inline const Real&
  getEfficiency() const noexcept;

  /**
   * @brief Get the reaction efficiency (mutable).
   * @return Probability that an impinging particle triggers this reaction.
   */
  inline Real&
  getEfficiency() noexcept;

protected:
  /**
   * @brief Source reactant index.
   */
  size_t m_reactant;

  /**
   * @brief Plasma product indices
   */
  std::list<size_t> m_products;

  /**
   * @brief Surface species consumed by the reaction.
   */
  std::list<size_t> m_surfaceReactants;

  /**
   * @brief Surface species produced by the reaction.
   */
  std::list<size_t> m_surfaceProducts;

  /**
   * @brief Reaction efficiency
   */
  Real m_efficiency;
};
} // namespace ItoKMC
} // namespace Physics

#include <CD_NamespaceFooter.H>

#include <CD_ItoKMCSurfaceReactionImplem.H>

#endif
